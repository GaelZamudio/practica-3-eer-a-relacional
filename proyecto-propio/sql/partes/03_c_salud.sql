CREATE TABLE animal (
    id_animal INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100),
    CONSTRAINT pk_animal PRIMARY KEY (id_animal)
);

CREATE TABLE persona (
    id_persona INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100),
    CONSTRAINT pk_persona PRIMARY KEY (id_persona)
);

CREATE TABLE veterinario_voluntario (
    id_persona INTEGER NOT NULL,
    CONSTRAINT pk_veterinario_voluntario PRIMARY KEY (id_persona),
    CONSTRAINT fk_veterinario_voluntario_persona FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);
CREATE TABLE clinica (
    id_clinica INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    direccion VARCHAR(200) NOT NULL,
    telefono VARCHAR(20),
    tipo VARCHAR(30) NOT NULL,
    CONSTRAINT pk_clinica PRIMARY KEY (id_clinica)
);
 
CREATE TABLE vacuna (
    id_vacuna INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    especie_destino VARCHAR(50) NOT NULL,
    intervalo_refuerzo_dias INTEGER,
    CONSTRAINT pk_vacuna PRIMARY KEY (id_vacuna),
    CONSTRAINT ck_vacuna_intervalo_refuerzo_dias CHECK (intervalo_refuerzo_dias IS NULL OR intervalo_refuerzo_dias > 0)
);
 
CREATE TABLE atencion_medica (
    id_animal INTEGER NOT NULL,
    num_atencion INTEGER NOT NULL,
    fecha DATE NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    observaciones TEXT,
    id_persona INTEGER,
    id_clinica INTEGER,
    CONSTRAINT pk_atencion_medica PRIMARY KEY (id_animal, num_atencion),
    CONSTRAINT ck_atencion_medica_num_atencion CHECK (num_atencion > 0),
    CONSTRAINT fk_atencion_medica_animal FOREIGN KEY (id_animal)
        REFERENCES animal (id_animal)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_atencion_medica_veterinario_voluntario FOREIGN KEY (id_persona)
        REFERENCES veterinario_voluntario (id_persona)
        ON DELETE SET NULL
        ON UPDATE CASCADE,
    CONSTRAINT fk_atencion_medica_clinica FOREIGN KEY (id_clinica)
        REFERENCES clinica (id_clinica)
        ON DELETE SET NULL
        ON UPDATE CASCADE
);
 
CREATE TABLE vacunacion (
    id_animal INTEGER NOT NULL,
    num_atencion INTEGER NOT NULL,
    dosis_num INTEGER NOT NULL,
    fecha_proxima_dosis DATE,
    id_vacuna INTEGER NOT NULL,
    CONSTRAINT pk_vacunacion PRIMARY KEY (id_animal, num_atencion),
    CONSTRAINT ck_vacunacion_dosis_num CHECK (dosis_num > 0),
    CONSTRAINT fk_vacunacion_atencion_medica FOREIGN KEY (id_animal, num_atencion)
        REFERENCES atencion_medica (id_animal, num_atencion)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_vacunacion_vacuna FOREIGN KEY (id_vacuna)
        REFERENCES vacuna (id_vacuna)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);
 
CREATE TABLE cirugia (
    id_animal INTEGER NOT NULL,
    num_atencion INTEGER NOT NULL,
    tipo_cirugia VARCHAR(100) NOT NULL,
    complicaciones TEXT,
    CONSTRAINT pk_cirugia PRIMARY KEY (id_animal, num_atencion),
    CONSTRAINT fk_cirugia_atencion_medica FOREIGN KEY (id_animal, num_atencion)
        REFERENCES atencion_medica (id_animal, num_atencion)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);
 
CREATE TABLE tratamiento (
    id_animal INTEGER NOT NULL,
    num_atencion INTEGER NOT NULL,
    diagnostico TEXT NOT NULL,
    duracion_dias INTEGER,
    CONSTRAINT pk_tratamiento PRIMARY KEY (id_animal, num_atencion),
    CONSTRAINT ck_tratamiento_duracion_dias CHECK (duracion_dias IS NULL OR duracion_dias > 0),
    CONSTRAINT fk_tratamiento_atencion_medica FOREIGN KEY (id_animal, num_atencion)
        REFERENCES atencion_medica (id_animal, num_atencion)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);
